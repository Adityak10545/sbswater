/*------------------------------------------
    SEO BUILD - writes the <head> SEO block of every page listed in
    seo.config.mjs, plus robots.txt and sitemap.xml at the site root.
    Idempotent: re-running replaces the block between the SEO markers and
    strips any older, hand-written copies of the same tags.

    Usage: npm run seo:build
-------------------------------------------*/
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import {
    SITE_URL,
    SITE_NAME,
    LOCALE,
    HTML_LANG,
    DEFAULT_IMAGE,
    ORGANIZATION,
    INTEGRATIONS,
    PAGES,
} from "./seo.config.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const BEGIN = "<!-- SEO:BEGIN - generated by scripts/seo/build-seo.mjs, edit scripts/seo/seo.config.mjs -->";
const END = "<!-- SEO:END -->";
const BODY_BEGIN = "<!-- SEO:BODY:BEGIN -->";
const BODY_END = "<!-- SEO:BODY:END -->";

const ORG_ID = SITE_URL + "/#organization";
const SITE_ID = SITE_URL + "/#website";

export function pageUrl(page) {
    return SITE_URL + (page.path || "/" + page.file);
}

const absolute = (path) => SITE_URL + "/" + path.replace(/^\//, "");
const byFile = Object.fromEntries(PAGES.map((p) => [p.file, p]));

function attr(value) {
    return String(value)
        .replace(/&/g, "&amp;")
        .replace(/"/g, "&quot;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;");
}

function text(value) {
    return String(value)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;");
}

function organizationNode() {
    const o = ORGANIZATION;
    return {
        "@type": "Organization",
        "@id": ORG_ID,
        name: o.name,
        alternateName: o.alternateName,
        url: SITE_URL + "/",
        logo: {
            "@type": "ImageObject",
            url: absolute(o.logo),
        },
        image: absolute(DEFAULT_IMAGE.path),
        email: o.email,
        telephone: o.telephone,
        foundingDate: o.foundingDate,
        address: { "@type": "PostalAddress", ...o.address },
        contactPoint: o.contactPoints.map((c) => ({
            "@type": "ContactPoint",
            ...c,
            areaServed: "IN",
            availableLanguage: "English",
        })),
        sameAs: o.sameAs,
    };
}

function structuredData(page) {
    const graph = [];
    const url = pageUrl(page);

    if (page.home) {
        graph.push(organizationNode());
        graph.push({
            "@type": "WebSite",
            "@id": SITE_ID,
            url: SITE_URL + "/",
            name: SITE_NAME,
            alternateName: ORGANIZATION.alternateName,
            inLanguage: HTML_LANG,
            publisher: { "@id": ORG_ID },
        });
    }

    if (page.service) {
        graph.push({
            "@type": "Service",
            "@id": url + "#service",
            name: page.service.name,
            serviceType: page.service.serviceType,
            description: page.description,
            url,
            provider: {
                "@type": "Organization",
                "@id": ORG_ID,
                name: ORGANIZATION.name,
                url: SITE_URL + "/",
            },
            areaServed: { "@type": "Country", name: "India" },
        });
    }

    if (page.breadcrumb) {
        graph.push({
            "@type": "BreadcrumbList",
            "@id": url + "#breadcrumb",
            itemListElement: page.breadcrumb.map(([name, file], i) => ({
                "@type": "ListItem",
                position: i + 1,
                name,
                item: pageUrl(byFile[file]),
            })),
        });
    }

    if (!graph.length) return "";
    const json = JSON.stringify(
        { "@context": "https://schema.org", "@graph": graph },
        null,
        2,
    ).replace(/<\//g, "<\\/");
    return `<script type="application/ld+json">\n${json}\n</script>`;
}

function headBlock(page) {
    const url = pageUrl(page);
    const image = absolute(DEFAULT_IMAGE.path);
    const lines = [BEGIN, `<title>${text(page.title)}</title>`];

    lines.push(`<meta name="description" content="${attr(page.description)}">`);
    if (page.index) {
        lines.push(`<meta name="robots" content="index, follow, max-image-preview:large">`);
        lines.push(`<link rel="canonical" href="${attr(url)}">`);
    } else {
        lines.push(`<meta name="robots" content="noindex, follow">`);
    }

    if (page.home && INTEGRATIONS.googleSiteVerification) {
        lines.push(
            `<meta name="google-site-verification" content="${attr(INTEGRATIONS.googleSiteVerification)}">`,
        );
    }

    lines.push(
        `<meta property="og:locale" content="${LOCALE}">`,
        `<meta property="og:type" content="website">`,
        `<meta property="og:site_name" content="${attr(SITE_NAME)}">`,
        `<meta property="og:title" content="${attr(page.title)}">`,
        `<meta property="og:description" content="${attr(page.description)}">`,
    );
    if (page.index) lines.push(`<meta property="og:url" content="${attr(url)}">`);
    lines.push(
        `<meta property="og:image" content="${attr(image)}">`,
        `<meta property="og:image:width" content="${DEFAULT_IMAGE.width}">`,
        `<meta property="og:image:height" content="${DEFAULT_IMAGE.height}">`,
        `<meta property="og:image:alt" content="${attr(DEFAULT_IMAGE.alt)}">`,
        `<meta name="twitter:card" content="summary_large_image">`,
        `<meta name="twitter:title" content="${attr(page.title)}">`,
        `<meta name="twitter:description" content="${attr(page.description)}">`,
        `<meta name="twitter:image" content="${attr(image)}">`,
    );

    for (const p of page.preload || []) {
        const type = p.type ? ` type="${attr(p.type)}"` : "";
        lines.push(
            `<link rel="preload" as="image" href="${attr(p.href)}"${type} media="${attr(p.media)}" fetchpriority="high">`,
        );
    }

    if (INTEGRATIONS.gtmId) {
        const id = attr(INTEGRATIONS.gtmId);
        lines.push(
            `<script>(function(w,d,s,l,i){w[l]=w[l]||[];w[l].push({'gtm.start':new Date().getTime(),event:'gtm.js'});var f=d.getElementsByTagName(s)[0],j=d.createElement(s),dl=l!='dataLayer'?'&l='+l:'';j.async=true;j.src='https://www.googletagmanager.com/gtm.js?id='+i+dl;f.parentNode.insertBefore(j,f);})(window,document,'script','dataLayer','${id}');</script>`,
        );
    }

    if (INTEGRATIONS.gaMeasurementId) {
        const id = attr(INTEGRATIONS.gaMeasurementId);
        lines.push(
            `<script async src="https://www.googletagmanager.com/gtag/js?id=${id}"></script>`,
            `<script>window.dataLayer=window.dataLayer||[];function gtag(){dataLayer.push(arguments);}gtag('js',new Date());gtag('config','${id}');</script>`,
        );
    }

    const ld = structuredData(page);
    if (ld) lines.push(ld);
    lines.push(END);
    return lines;
}

// Older, hand-written SEO tags that the generated block replaces.
const LEGACY_TAGS = [
    /<title>[\s\S]*?<\/title>/gi,
    /<meta\s+name="description"[^>]*>/gi,
    /<meta\s+name="robots"[^>]*>/gi,
    /<meta\s+name="google-site-verification"[^>]*>/gi,
    /<meta\s+property="og:[^"]*"[^>]*>/gi,
    /<meta\s+name="twitter:[^"]*"[^>]*>/gi,
    /<link\s+rel="canonical"[^>]*>/gi,
];

function stripLine(html, re) {
    // remove the tag together with its indentation and line break
    const src = re.source;
    const line = new RegExp(`[ \\t]*(?:${src})[ \\t]*\\r?\\n?`, re.flags);
    return html.replace(line, "");
}

function processPage(page) {
    const file = resolve(ROOT, page.file);
    if (!existsSync(file)) throw new Error(`Missing page: ${page.file}`);
    let html = readFileSync(file, "utf8");
    const eol = html.includes("\r\n") ? "\r\n" : "\n";

    // previous generated blocks
    html = html.replace(
        new RegExp(`[ \\t]*${escapeRe(BEGIN.slice(0, 14))}[\\s\\S]*?${escapeRe(END)}[ \\t]*\\r?\\n?`, "g"),
        "",
    );
    html = html.replace(
        new RegExp(`[ \\t]*${escapeRe(BODY_BEGIN)}[\\s\\S]*?${escapeRe(BODY_END)}[ \\t]*\\r?\\n?`, "g"),
        "",
    );
    for (const re of LEGACY_TAGS) html = stripLine(html, re);

    html = html.replace(/<html lang="[^"]*"/i, `<html lang="${HTML_LANG}"`);

    const anchor = html.match(/([ \t]*)<meta\s+name="theme-color"[^>]*>[ \t]*\r?\n/i);
    if (!anchor) throw new Error(`No theme-color meta to anchor on in ${page.file}`);
    const indent = anchor[1];
    const block = headBlock(page)
        .join("\n")
        .split("\n")
        .map((l) => indent + l)
        .join(eol);
    html = html.replace(anchor[0], anchor[0] + block + eol);

    if (INTEGRATIONS.gtmId) {
        const id = attr(INTEGRATIONS.gtmId);
        const noscript = `${BODY_BEGIN}<noscript><iframe src="https://www.googletagmanager.com/ns.html?id=${id}" height="0" width="0" style="display:none;visibility:hidden"></iframe></noscript>${BODY_END}`;
        html = html.replace(/(<body[^>]*>)(\r?\n?)/i, `$1$2${noscript}${eol}`);
    }

    writeFileSync(file, html);
}

function escapeRe(s) {
    return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function writeSitemap() {
    const urls = PAGES.filter((p) => p.index).map(
        (p) => `  <url>\n    <loc>${text(pageUrl(p))}</loc>\n  </url>`,
    );
    const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join("\n")}\n</urlset>\n`;
    writeFileSync(resolve(ROOT, "sitemap.xml"), xml);
    return urls.length;
}

function writeRobots() {
    const txt = [
        `# robots.txt for ${SITE_URL}`,
        "# Generated by scripts/seo/build-seo.mjs. Pages kept out of search use",
        "# <meta name=\"robots\" content=\"noindex\"> instead of Disallow, so",
        "# crawlers can still read that directive.",
        "",
        "User-agent: *",
        "Allow: /",
        "",
        `Sitemap: ${SITE_URL}/sitemap.xml`,
        "",
    ].join("\n");
    writeFileSync(resolve(ROOT, "robots.txt"), txt);
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
    for (const page of PAGES) processPage(page);
    const count = writeSitemap();
    writeRobots();
    console.log(`SEO block written to ${PAGES.length} pages; sitemap.xml has ${count} URLs; robots.txt written.`);
}
